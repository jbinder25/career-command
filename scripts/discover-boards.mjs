#!/usr/bin/env node
// Find job boards for the company names in knowledge/job-agent/company-seeds.txt and write the ones that
// answer to knowledge/job-agent/open-boards.json (merged with what is already there). The daily scan reads
// every board in that file, not just the favorites in companies.json.
//
//   node scripts/discover-boards.mjs            resolve every seed that has no board yet
//   node scripts/discover-boards.mjs --recheck  resolve all seeds again
//
// A Greenhouse board is accepted only when the board's own name matches the seed, so a slug that happens to
// belong to a different company is rejected. Ashby and Lever do not publish a board name, so they are accepted
// only when the slug is exactly the company name (joined or dashed).
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const agent = require('../api/_lib/job-agent');
const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const seedsFile = path.join(root, 'knowledge/job-agent/company-seeds.txt');
const outFile = path.join(root, 'knowledge/job-agent/open-boards.json');
const recheck = process.argv.includes('--recheck');

const norm = s => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
const lines = fs.readFileSync(seedsFile, 'utf8').split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#'));
const excluded = new Set(lines.filter(l => l.startsWith('!')).map(l => norm(l.slice(1))));
const seeds = [...new Set(lines.filter(l => !l.startsWith('!')))];
const existing = fs.existsSync(outFile) ? JSON.parse(fs.readFileSync(outFile, 'utf8')) : { boards: [] };
const have = new Map(existing.boards.map(b => [norm(b.name), b]));
const favorites = new Set(agent.COMPANIES.map(c => norm(c.name)));
const todo = seeds.filter(n => !favorites.has(norm(n)) && (recheck || !have.has(norm(n))));

async function get(url) {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(15000), headers: { accept: 'application/json' } });
    return res.ok ? res.json() : null;
  } catch (e) { return null; }
}

async function resolve(name) {
  const n = norm(name);
  const guesses = agent.slugGuesses(name);
  const exact = new Set([n, name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')]);
  for (const slug of guesses) {
    const info = await get(`https://boards-api.greenhouse.io/v1/boards/${slug}`);
    if (info && info.name) {
      const b = norm(info.name);
      if (b === n || (n.length >= 4 && (b.includes(n) || n.includes(b)) && Math.min(b.length, n.length) >= 4)) {
        const jobs = await get(`https://boards-api.greenhouse.io/v1/boards/${slug}/jobs`);
        if (jobs && (jobs.jobs || []).length) return { name: info.name, board: 'greenhouse:' + slug, jobs: jobs.jobs.length };
      }
    }
  }
  for (const slug of guesses.filter(s => exact.has(s))) {
    const a = await get(`https://api.ashbyhq.com/posting-api/job-board/${slug}`);
    if (a && (a.jobs || []).length) return { name, board: 'ashby:' + slug, jobs: a.jobs.length };
  }
  for (const slug of guesses.filter(s => exact.has(s))) {
    const l = await get(`https://api.lever.co/v0/postings/${slug}?mode=json`);
    if (Array.isArray(l) && l.length && String(l[0].hostedUrl || '').includes('/' + slug + '/')) return { name, board: 'lever:' + slug, jobs: l.length };
  }
  return null;
}

let next = 0, found = 0;
const results = [];
await Promise.all(Array.from({ length: 16 }, async () => {
  while (next < todo.length) {
    const name = todo[next++];
    const r = await resolve(name);
    if (r) { found++; results.push(r); }
    process.stderr.write(`\r${next}/${todo.length} checked, ${found} boards found   `);
  }
}));
process.stderr.write('\n');

const merged = new Map(existing.boards.map(b => [b.board, b]));
for (const r of results) merged.set(r.board, { name: r.name, board: r.board });
const boards = [...merged.values()].sort((a, b) => a.name.localeCompare(b.name));
// two seeds can resolve to one company; keep one entry per company name
const byName = new Map();
for (const b of boards) if (!excluded.has(norm(b.name)) && !byName.has(norm(b.name))) byName.set(norm(b.name), b);
fs.writeFileSync(outFile, JSON.stringify({
  _note: 'Generated by scripts/discover-boards.mjs from company-seeds.txt. The daily scan reads every board here in addition to the favorites in companies.json. Safe to edit by hand.',
  boards: [...byName.values()],
}, null, 1) + '\n');
console.log(`${results.length} new boards (${byName.size} total) written to ${path.relative(root, outFile)}`);
console.log('not found:', todo.filter(n => !results.some(r => norm(r.name) === norm(n) || r.board.endsWith(':' + norm(n)))).length);
